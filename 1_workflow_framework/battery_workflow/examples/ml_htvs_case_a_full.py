"""
Case A, end to end -- replay, execute, retrieve, suggest, on one coordinator
============================================================================

The three earlier Case A scripts each show one thing. ``ml_htvs_screening.py``
replays the published 438 -> 319 -> 306 -> 56 funnel; ``ml_htvs_continuation.py``
executes a second released model on the 56 survivors. Neither answers the
question a shortlist actually raises next: these compositions have no measured
conductivity and no published successor stage, so what does the literature
already know about them, and what should be done with them?

This script runs the whole chain through one ``Coordinator``:

    HTPredictor (lookup)        56 published electrochemical survivors
      -> ProcessCoordinator     composition -> formula
    HTPredictor (executed)      ML-SSE model.joblib, 56 real predictions
      -> ProcessCoordinator     formula + executed flags
    SimulationFeedback          published AIMD trajectories (LiSSE-MP), if any
      -> ProcessCoordinator     retrieval target + executed flags carried on
    KnowledgeMiner              BatteryQA over the authors' corpus, deep dive only
      -> ProcessCoordinator     family + citation counts
    MechanismSimulator          the structures the release enumerated, if any
      -> ProcessCoordinator     structure availability
    FormulationDesigner         fixed rules -> cited next steps

All six role interfaces are dispatched on real data in a single run. The
Experiment Feedback interface runs at simulation grade: LiSSE-MP (audit
paper_id 10664) published AIMD trajectories for nine superionic conductors,
one of which shares its exact stoichiometry with a survivor, so the feedback
stage serves those published virtual experiments. This run uses no measurement,
and the three linked releases contain no measured-cell result that is used
here; every feedback row is labelled simulation.

Cost is why the last four stages run on the deep-dive compositions only. The
deep-dive rule is exported with the run: the top ``--cards`` compositions by
executed conductivity, plus any survivor whose exact stoichiometry has a
published AIMD study. That second clause was declared post hoc, after the
AIMD match for LiAlS2 (rank 40) had been seen; it is an illustrative
coordination rule, not a selection policy fixed in advance, and the run record
says so. What it surfaces is condition-mismatched evidence: the release labels
LiAlS2 superionic from 800-1700 K structure-specific AIMD, while the executed
composition-level estimate sits below the 1e-4 S/cm convention. The two are
not directly comparable, and the chain records the mismatch for aligned
reassessment instead of judging either tool right.

What this is not
----------------
A validation. The ranking is ML-SSE's own prediction, executed but unmeasured;
the retrieval says what a 723-paper corpus contains, not what is true; the
suggestions are rule outputs, not a design. No gate is invented anywhere in the
chain -- 1e-4 S/cm is annotated as a field convention and never enforced.

Reproducibility is layered, and the export states it per stage. Coordination
(``deterministic=True``), the ML-SSE execution, the fixed rules, and the AIMD
lookup over pinned bytes are deterministic given the recorded environment.
Retrieval is stable but not bit-exact: embedding scores move in the third
decimal, so a paper near the relevance floor can enter or leave the retained
set between runs. The card's prose is generated by a model from the retrieved
passages and varies freely; counts and citation keys are facts of one exported
run, not run-invariants.

Usage
-----
    python battery_workflow/examples/ml_htvs_case_a_full.py [--cards N]

Environment: ``BATTAGENT_PAPERQA_DIR`` and ``BATTAGENT_PAPERQA_PYTHON`` for the
retrieval backend, ``BATTAGENT_ML_SSE_PYTHON`` for the sklearn 1.0.x interpreter
that unpickles ML-SSE, ``BATTAGENT_ML_HTVS_DIR`` / ``BATTAGENT_REPOS_CACHE`` for
the pinned clones.
"""


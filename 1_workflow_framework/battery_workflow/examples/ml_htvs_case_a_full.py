#: Every survivor is carried and executed; only the top-ranked few are worth a
#: literature retrieval, which costs an embedding call per question and a model
#: call per card.
SHORTLIST_PIPELINE = [
    ("PropertyScreener", "predict_material_properties"),
    ("ExecutedToolScreener", "predict_ionic_conductivity"),
]

DEEP_DIVE_PIPELINE = SHORTLIST_PIPELINE + [
    ("SimulationFeedback", "simulation_feedback"),
    ("KnowledgeMiner", "retrieve_literature_card"),
    ("MechanismSimulator", "enumerate_published_structures"),
    ("FormulationDesigner", "suggest_next_steps"),
]

#: Field protocol for the chain. Every mapping names a metric an upstream agent
#: actually recorded; a target agent that needs one refuses to proceed without it.
HANDOFF_FIELDS = {
    "PropertyScreener->ExecutedToolScreener": {
        "formula": "composition",
    },
    "ExecutedToolScreener->SimulationFeedback": {
        "formula": "formula",
        "executed_log10_sigma": "log10_sigma",
        "executed_above_convention": "above_convention_1e4",
    },
    "SimulationFeedback->KnowledgeMiner": {
        "retrieval_target": "formula",
        "executed_log10_sigma": "executed_log10_sigma",
        "executed_above_convention": "executed_above_convention",
    },
    "KnowledgeMiner->MechanismSimulator": {
        "literature_family": "family",
        "literature_n_cited": "n_cited",
    },
    "MechanismSimulator->FormulationDesigner": {
        "structures_published": "published_structures",
        "structure_data_published": "structure_data_published",
        "literature_family": "literature_family",
    },
}

HANDOFF_EDGES = {
    "PropertyScreener": "ExecutedToolScreener",
    "ExecutedToolScreener": "SimulationFeedback",
    "SimulationFeedback": "KnowledgeMiner",
    "KnowledgeMiner": "MechanismSimulator",
    "MechanismSimulator": "FormulationDesigner",
}

#: No stage in this chain has a published acceptance criterion, and none is
#: invented: the ML-HTVS cascade already ran upstream, ML-SSE's notebooks state
#: no threshold, and neither retrieval nor a rule engine is a gate.
GATE_MAP = {name: [] for name, _ in DEEP_DIVE_PIPELINE}

DEFAULT_CARDS = 5
DEFAULT_OUTDIR = Path(__file__).resolve().parents[2] / "results" / "case_a_full"


def build_coordinator(
    predictions, how, weight_sha256, dataset, knowledge_backend,
    aimd_index, sigma_by_mpid, sigma_how,
) -> Coordinator:
    coordinator = Coordinator(
        pipeline=SHORTLIST_PIPELINE,
        gate_map=GATE_MAP,
        handoff_edges=HANDOFF_EDGES,
        deterministic=True,
    )
    coordinator.register_module("PropertyScreener", HtvsSurvivorCarrier())
    coordinator.register_module(
        "ExecutedToolScreener", ExecutedToolScreener(predictions, how, weight_sha256)
    )
    coordinator.register_module(
        "SimulationFeedback", PublishedAimdFeedback(aimd_index, sigma_by_mpid, sigma_how)
    )
    coordinator.register_module("KnowledgeMiner", KnowledgeMiner(backend=knowledge_backend))
    coordinator.register_module("MechanismSimulator", HtvsStructureBuilder(dataset))
    coordinator.register_module("FormulationDesigner", ShortlistFormulationDesigner(
        source_note="rule-based over executed ML-SSE metrics, the retrieved card, "
                    "and the published virtual feedback"
    ))
    coordinator.register_module("ProcessCoordinator", ProcessCoordinator(HANDOFF_FIELDS))
    return coordinator


def _agent_coverage(trace: list[dict], deep_dive_desc: str) -> list[dict]:
    """One row per architecture role, with the deep-dive set described exactly."""
    def steps(*stages: str) -> int:
        return sum(1 for s in trace if s.get("stage") in stages)

    return [
        {
            "role": "HT Predictor",
            "modules": "PropertyScreener (lookup) + ExecutedToolScreener (executed)",
            "status": "ran",
            "steps": steps("PropertyScreener", "ExecutedToolScreener"),
            "basis": "published survivor rows, then the released ML-SSE model executed",
        },
        {
            "role": "Process Coordinator",
            "modules": "ProcessCoordinator",
            "status": "ran",
            "steps": sum(1 for s in trace if s.get("kind") == "handoff"),
            "basis": "field translation between every adjacent pair of stages",
        },
        {
            "role": "Knowledge Miner",
            "modules": "KnowledgeMiner",
            "status": "ran",
            "steps": steps("KnowledgeMiner"),
            "basis": f"BatteryQA retrieval over the authors' corpus for the {deep_dive_desc}",
        },
        {
            "role": "Mechanism Simulator",
            "modules": "MechanismSimulator",
            "status": "ran",
            "steps": steps("MechanismSimulator"),
            "basis": "the structures the ML-HTVS release enumerated, or the recorded absence",
        },
        {
            "role": "Formulation Designer",
            "modules": "FormulationDesigner",
            "status": "ran",
            "steps": steps("FormulationDesigner"),
            "basis": "fixed rules over the executed metrics, the retrieved card, and "
                     "the published virtual feedback",
        },
        {
            "role": "Experiment Feedback",
            "modules": "SimulationFeedback (published AIMD)",
            "status": "ran (simulation-grade)",
            "steps": steps("SimulationFeedback"),
            "basis": "published AIMD trajectories (LiSSE-MP) served as virtual "
                     "experiments; this run used no measurement, the linked "
                     "releases provided none that is used here, and every row is "
                     "labelled simulation, not measurement",
        },
    ]


def run_case_a_full(
    htvs_root: str | None = None,
    sse_root: str | None = None,
    lisse_root: str | None = None,
    n_cards: int = DEFAULT_CARDS,
    require_real_backend: bool = True,
) -> dict:
    force_utf8_stdout()

    print("=" * 78)
    print("Case A, end to end - replay, execute, virtual-check, retrieve, suggest")
    print("=" * 78)

    dataset = ml_htvs.load(htvs_root)
    shortlist = list(dataset.published_survivors["electrochemical"])
    if len(shortlist) != 56:
        raise RuntimeError(f"expected 56 published survivors, got {len(shortlist)}")

    sse_source = ml_sse.SOURCE
    sse_source.verify(sse_root)
    sse_dir = sse_source.root(sse_root)
    weight_sha = sse_source.files["model.joblib"]
    if _sha256(sse_dir / "model.joblib") != weight_sha:
        raise RuntimeError("ML-SSE model.joblib checksum mismatch")

    aimd_index = lisse_mp.load(lisse_root)

    backend = get_knowledge_backend(top_k=6)
    if require_real_backend and backend.name == "stub":
        raise RuntimeError(
            "KnowledgeMiner would run on the deterministic stub. Set "
            "BATTAGENT_PAPERQA_DIR to the directory holding battery_qa.py (and "
            "BATTAGENT_PAPERQA_PYTHON to an interpreter with the index), or pass "
            "require_real_backend=False to run the chain without literature cards."
        )

    print(f"\nUpstream shortlist : {ml_htvs.SOURCE.tool} {ml_htvs.SOURCE.citation}")
    print(f"  compositions     : {len(shortlist)} published electrochemical survivors")
    print(f"Executed tool      : {sse_source.tool} {sse_source.citation}")
    print(f"  model            : model.joblib @ {weight_sha[:12]}...")
    print(f"Virtual experiments: {lisse_mp.SOURCE.tool} {lisse_mp.SOURCE.citation}")
    print(f"  AIMD structures  : {len(aimd_index.structures)} published trajectories, "
          f"{len(lisse_mp.TEMPERATURES_K)} temperatures each")
    print(f"Knowledge backend  : {backend.name}")
    print(f"  deep dive        : top {n_cards} by executed conductivity, plus any "
          "survivor with an exact-composition AIMD study")
    print("  no accept/reject gate anywhere in this chain.")

    # One batch call loads the 21 MB forest once; the coordinator then serves each
    # candidate its own row. The ranking below therefore uses the same executed
    # values the ExecutedToolScreener reports, not a second calculation.
    training_elements = ml_sse.training_elements(sse_dir)
    rows, how = predict_formulas(sse_dir, shortlist, training_elements)
    by_formula = {row.formula: row for row in rows}
    print(f"  execution        : {how}")

    ranked = sorted(
        (
            {
                "composition": r.formula,
                "log10_sigma": r.log10_sigma,
                "sigma_S_cm": r.sigma_S_cm,
                "above_convention_1e4": r.above_convention_1e4,
                "ood_elements": ",".join(r.ood_elements),
                "execution": True,
            }
            for r in rows
        ),
        key=lambda row: row["log10_sigma"],
        reverse=True,
    )
    for index, row in enumerate(ranked, start=1):
        row["rank"] = index

    # Deep-dive rule, exported with the run: the top n_cards by executed
    # conductivity, plus every survivor whose exact stoichiometry has a
    # published AIMD study. The second clause is a coordination decision --
    # a published virtual experiment exists, so the candidate is worth the
    # retrieval cost regardless of its rank.
    aimd_matched = [
        row["composition"] for row in ranked
        if aimd_index.exact_match(row["composition"])
    ]
    deep_dive = [row["composition"] for row in ranked[:n_cards]]
    deep_dive += [c for c in aimd_matched if c not in deep_dive]
    deep_dive_rule = (
        f"top {n_cards} by executed log10 conductivity, plus any survivor whose "
        "exact stoichiometry has a published AIMD trajectory in LiSSE-MP. The "
        "second clause was declared post hoc, after the AIMD match had been "
        "seen; illustrative, not a selection policy fixed in advance"
    )
    for row in ranked:
        row["literature_card"] = row["composition"] in deep_dive
        row["aimd_exact_match"] = row["composition"] in aimd_matched

    # Deserialize the published analysis objects once per matched structure.
    sigma_by_mpid: dict[str, list] = {}
    sigma_how = "not attempted: no exact match"
    for composition in aimd_matched:
        structure = aimd_index.exact_match(composition)
        points, sigma_how = analyze_trajectories(aimd_index.trajectory_paths(structure))
        sigma_by_mpid[structure.mp_id] = points

    coordinator = build_coordinator(
        by_formula, how, weight_sha, dataset, backend,
        aimd_index, sigma_by_mpid, sigma_how,
    )

    print("\n" + "-" * 78)
    print(f"RUNNING  ({len(shortlist)} candidates, {len(deep_dive)} with the full chain: "
          f"top {n_cards} + {len(aimd_matched)} AIMD-matched)")
    print("-" * 78)

    for composition in shortlist:
        deep = composition in deep_dive
        coordinator.pipeline = DEEP_DIVE_PIPELINE if deep else SHORTLIST_PIPELINE
        coordinator.create_candidate(
            candidate_id=f"case-a-full:{composition}",
            system_name=composition,
            components=[ComponentSpec(role="electrolyte", composition=composition)],
            test_conditions={"continuation_of": "ml_htvs_screening",
                             "deep_dive": deep},
        )
        coordinator.run(
            f"case-a-full:{composition}",
            objective=(
                "ground a screened lithium solid electrolyte in an executed conductivity "
                "model and in the literature for its family"
            ),
            max_iterations=1,
        )
        if deep:
            print(f"  {composition:<14} executed + card retrieved")

    # ----- Collect what the deep-dive candidates produced -----
    cards: list[dict] = []
    card_papers: list[dict] = []
    suggestions: list[dict] = []
    feedback_rows: list[dict] = []
    for composition in deep_dive:
        record = coordinator.mkb.get(f"case-a-full:{composition}")
        card = record.test_conditions.get("_knowledge_card", {})
        km = record.get_latest_metrics("KnowledgeMiner")
        fd = record.get_latest_metrics("FormulationDesigner")
        ms = record.get_latest_metrics("MechanismSimulator")
        fb = record.get_latest_metrics("SimulationFeedback")
        rank = next(r["rank"] for r in ranked if r["composition"] == composition)
        context = composition_context(composition)

        feedback_row = {
            "rank": rank,
            "composition": composition,
            "feedback_grade": fb.get("feedback_grade", ""),
            "measurement_used_in_this_run": fb.get("measurement_used_in_this_run", False),
            "aimd_exact_match": fb.get("aimd_exact_match", False),
            "aimd_exact_mp_id": fb.get("aimd_exact_mp_id", ""),
            "aimd_family_mp_ids": fb.get("aimd_family_mp_ids", ""),
            "aimd_family_formulas": fb.get("aimd_family_formulas", ""),
            "no_published_simulation": fb.get("no_published_simulation", False),
            "condition_mismatched_evidence": fb.get("condition_mismatched_evidence", False),
            "executed_log10_sigma": fb.get("executed_log10_sigma"),
            "executed_above_convention": fb.get("executed_above_convention"),
            "aimd_numbers_available": fb.get("aimd_numbers_available", False),
            "aimd_analysis_how": fb.get("aimd_analysis_how", ""),
            "aimd_pymatgen_version": fb.get("aimd_pymatgen_version", ""),
            "aimd_analyzer_module": fb.get("aimd_analyzer_module", ""),
            "n_aimd_structures_scanned": fb.get("n_aimd_structures_scanned", 0),
            "release_claim": fb.get("release_claim", ""),
        }
        for temp in lisse_mp.TEMPERATURES_K:
            feedback_row[f"aimd_sigma_mS_cm_{temp}K"] = fb.get(f"aimd_sigma_mS_cm_{temp}K")
            feedback_row[f"aimd_diffusivity_cm2_s_{temp}K"] = fb.get(
                f"aimd_diffusivity_cm2_s_{temp}K"
            )
        feedback_rows.append(feedback_row)

        cards.append({
            "rank": rank,
            "composition": composition,
            "family": card.get("family", ""),
            "phrase_queried": context["phrase"],
            "backend": card.get("backend", ""),
            "n_papers": card.get("n_papers", 0),
            "n_family_term_papers": card.get("n_family_term_papers", 0),
            "n_cited": card.get("n_cited", 0),
            "n_failure_modes": len(card.get("failure_modes", [])),
            "n_conductivity_notes": len(card.get("conductivity_notes", [])),
            "n_family_precedent": len(card.get("family_precedent", [])),
            "hits_below_floor": card.get("hits_below_floor", 0),
            "relevance_floor": card.get("relevance_floor"),
            "corpus_miss": card.get("corpus_miss", True),
            "citations": ";".join(card.get("citations", [])),
            "citations_proposed": card.get("citation_audit", {}).get("proposed", 0),
            "citations_dropped": card.get("citation_audit", {}).get("dropped", 0),
            "corpus_verdict": card.get("corpus_verdict", "") or card.get("miss_note", ""),
            "structures_published": ms.get("published_structures", 0),
            "n_rules_fired": fd.get("n_rules_fired", 0),
            "km_backend_reported": km.get("backend", ""),
        })
        for paper in card.get("papers", []):
            card_papers.append({
                "composition": composition,
                "citekey": paper.get("citekey", ""),
                "title": paper.get("title", ""),
                "score": paper.get("score"),
                "family_term_match": ",".join(paper.get("family_term_match", [])),
                "matched_query": paper.get("matched_query", ""),
            })
        for rule in fd.get("rules_fired", []):
            spec = next(r for r in SUGGESTION_RULES if r["rule_id"] == rule)
            fired_citations = [
                c for s in _suggestions_of(record) if s["rule_id"] == rule for c in s["citations"]
            ]
            suggestions.append({
                "rank": rank,
                "composition": composition,
                "rule_id": rule,
                "condition": spec["condition"],
                "action": spec["action"],
                "citations": ";".join(fired_citations),
            })

    calibration = backend.calibrate_relevance() if hasattr(backend, "calibrate_relevance") else {}
    calibration_rows = calibration.get("probes", []) if isinstance(calibration, dict) else []

    trace = coordinator.agent_trace
    executed_steps = [s for s in trace if s.get("execution") is True]
    handoffs = [s for s in trace if s.get("kind") == "handoff"]
    km_steps = [s for s in trace if s.get("stage") == "KnowledgeMiner"]
    sf_steps = [s for s in trace if s.get("stage") == "SimulationFeedback"]
    gate_steps = [s for s in trace if s.get("kind") == "gate"]
    coverage = _agent_coverage(
        trace,
        f"{len(deep_dive)}-composition deep-dive set "
        f"(top {n_cards} + {len(aimd_matched)} AIMD exact match)",
    )

    # ----- Report -----
    print("\n" + "-" * 78)
    print("EXECUTED RANKING  (ML-SSE log10 ionic conductivity, top 10 of 56)")
    print("-" * 78)
    print(f"{'rank':<6}{'composition':<16}{'log10(S/cm)':>12}{'>=1e-4?':>9}{'OOD':>8}{'card':>7}")
    for row in ranked[:10]:
        print(f"{row['rank']:<6}{row['composition']:<16}{row['log10_sigma']:>12.3f}"
              f"{('yes' if row['above_convention_1e4'] else 'no'):>9}"
              f"{(row['ood_elements'] or '-'):>8}"
              f"{('yes' if row['literature_card'] else '-'):>7}")

    print("\n" + "-" * 78)
    print("LITERATURE CARDS  (real retrieval; counts are facts, prose is a model summary)")
    print("-" * 78)
    print(f"{'composition':<14}{'family':<44}{'papers':>7}{'cited':>7}{'fail':>6}")
    for card in cards:
        print(f"{card['composition']:<14}{card['family'][:42]:<44}"
              f"{card['n_papers']:>7}{card['n_cited']:>7}{card['n_failure_modes']:>6}")
    hit_cards = [c for c in cards if not c["corpus_miss"]]
    print(f"\n  {len(hit_cards)} of {len(cards)} compositions have corpus precedent above the "
          f"{cards[0]['relevance_floor'] if cards else 'n/a'} relevance floor")
    print(f"  citations proposed {sum(c['citations_proposed'] for c in cards)}, "
          f"dropped by the .bib whitelist {sum(c['citations_dropped'] for c in cards)}")

    print("\n" + "-" * 78)
    print("VIRTUAL FEEDBACK  (published AIMD served as simulation-grade evidence)")
    print("-" * 78)
    print(f"{'composition':<14}{'exact':>7}{'family':>8}{'mismatch':>10}   sigma(T) mS/cm")
    for row in feedback_rows:
        if row["aimd_numbers_available"]:
            sigma = "  ".join(
                f"{temp}K {row[f'aimd_sigma_mS_cm_{temp}K']:.2f}"
                for temp in lisse_mp.TEMPERATURES_K
                if row.get(f"aimd_sigma_mS_cm_{temp}K") is not None
            )
        else:
            sigma = "-"
        print(f"  {row['composition']:<14}"
              f"{(row['aimd_exact_mp_id'] or '-'):>9}"
              f"{(str(len(row['aimd_family_mp_ids'].split(','))) if row['aimd_family_mp_ids'] else '-'):>6}"
              f"{('YES' if row['condition_mismatched_evidence'] else '-'):>10}   {sigma}")
    mismatches = [r for r in feedback_rows if r["condition_mismatched_evidence"]]
    if mismatches:
        target = mismatches[0]
        print(f"\n  condition-mismatched evidence: the release labels {target['composition']} "
              "superionic from")
        print(f"  800-1700 K structure-specific AIMD, while the executed composition-level "
              f"estimate ranks it {target['rank']}/56")
        print("  below the 1e-4 S/cm convention. The two are not condition-aligned; the")
        print("  feedback stage records the mismatch for aligned reassessment, judging neither.")

    print("\n" + "-" * 78)
    print("NEXT-STEP SUGGESTIONS  (fixed rules; no composition proposed, no threshold invented)")
    print("-" * 78)
    for composition in deep_dive:
        fired = [s for s in suggestions if s["composition"] == composition]
        print(f"  {composition:<14} {len(fired)} of {len(SUGGESTION_RULES)} rules: "
              f"{', '.join(s['rule_id'] for s in fired)}")

    print("\n" + "-" * 78)
    print("AGENT COVERAGE")
    print("-" * 78)
    for row in coverage:
        print(f"  {row['role']:<22}{row['status']:<9}{row['steps']:>5} steps   {row['basis'][:60]}")

    print("\n" + "-" * 78)
    print("AGENT TRACE")
    print("-" * 78)
    print(f"  {len(trace)} recorded steps: "
          f"{sum(1 for s in trace if s['kind'] == 'agent')} agent invocations, "
          f"{len(handoffs)} field handoffs, "
          f"{len(executed_steps)} executed-model steps, "
          f"{len(km_steps)} retrieval steps, "
          f"{len(sf_steps)} virtual-feedback steps")
    print(f"  plan source : {coordinator.plan_source} "
          f"(deterministic={coordinator.deterministic})")

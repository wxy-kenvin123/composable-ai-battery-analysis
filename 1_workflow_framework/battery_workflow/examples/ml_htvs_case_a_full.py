def _suggestions_of(record) -> list[dict]:
    """The structured suggestions the FormulationDesigner wrote for this candidate."""
    for result in reversed(record.stage_results):
        if result.module_name == "FormulationDesigner":
            return json.loads(result.artifacts.get("suggestions_json", "[]"))
    return []


